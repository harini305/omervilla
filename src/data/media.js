export function media(stem) {
  const entry = manifest[stem];
  if (!entry) throw new Error(`Unknown media file: ${stem}`);
  const srcSet = entry.widths.map((w) => `/media/${stem}-${w}.webp ${w}w`).join(", ");
  const full = `/media/${stem}-${entry.width}.webp`;
  return {
    stem,
    src: full,
    srcSet,
    width: entry.width,
    height: entry.height,
    alt: ALT[stem] ?? "",
  };
}

export const mediaList = (stems) => stems.map(media);
